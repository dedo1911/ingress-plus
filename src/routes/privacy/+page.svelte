<div>
  <h1>Privacy Policy for Ingress Plus</h1>
    <p><em>Effective date: July 8th, 2025 (last updated: August 4th, 2026)</em></p>

    <p>Welcome, Agent, to Ingress Plus! This project was created to support the Ingress community and enhance your experience in the field.
    We take your privacy seriously. This Privacy Policy explains what information we collect, how we use it,
    and what choices you have about your data. We aim to be transparent so you can use Ingress Plus without worries.
    By using Ingress Plus or its related plugins, you agree to this Privacy Policy. Thank you for being part of the community — see you out there!</p>

    <h2>1. Personal Data Collected</h2>

    <h3>1.1 When Not Registered (Visitors)</h3>
    <p>When you access Ingress Plus without registering an account, the following data may be collected automatically:</p>
    <ul>
        <li>IP address</li>
        <li>Date and time a resource was requested</li>
        <li>User agent of your browser (Browser type, version, Operating System)</li>
        <li>URL of the requested resource</li>
        <li>URL of the referring page (Referrer)</li>
    </ul>

    <h3>1.2 When Registered (Users with Account)</h3>
    <p>When you register or log in via OAuth (currently supported provider: <a href="https://policies.google.com/?hl=en" target="_blank" rel="noopener noreferrer">Google</a>),
      we additionally collect the following data as provided by the OAuth service:</p>
    <ul>
        <li>Email address</li>
        <li>URL to your avatar</li>
        <li>Display name</li>
        <li>OAuth provider name and OAuth token</li>
    </ul>
    <p>Additionally, if set by the user:</p>
    <ul>
        <li>Agent name</li>
        <li>Faction</li>
    </ul>
    <p>Further data may be collected depending on which site features you use, for example:</p>
    <ul>
        <li>Acquired badges</li>
        <li>Text and pictures submitted via bug reports</li>
        <li>Supporter Status</li>
    </ul>

    <h3>1.3 When Submitting Media via the IITC Mediagress Plugin</h3>
    <p>When using the Mediagress plugin, we collect the following data:</p>
    <ul>
        <li>Ingress username as reported by IITC</li>
        <li>Media item data, including:
            <ul>
                <li>Timestamp of when the Media was acquired</li>
                <li>Internal Ingress player ID</li>
            </ul>
        </li>
        <li>IP address</li>
        <li>Date and time a resource was requested</li>
        <li>User agent of your browser (Browser type, version, Operating System)</li>
        <li>URL of the requested resource</li>
        <li>URL of the referring page (Referrer)</li>
    </ul>

    <h3>1.4 Data Stored on Your System</h3>
    <p>Ingress Plus may store the following data on your device:</p>
    <ul>
        <li>Cookies (for authentication)</li>
        <li>Site settings</li>
        <li>Timestamp of your last Media upload (plugin)</li>
        <li>List of uploaded Media (plugin)</li>
    </ul>

    <h3>1.5 Third-Party Resources Loaded By Your Browser</h3>
    <p>Regardless of whether you are registered, our website loads the "Exo" and "Kode Mono" fonts directly from
      <a href="https://policies.google.com/?hl=en" target="_blank" rel="noopener noreferrer">Google</a>'s Google Fonts
      servers rather than hosting them ourselves. As a result, your browser sends your IP address and standard
      request data (as described in section 1.1) directly to Google when a page loads.</p>

    <h3>1.6 Optional Third-Party Stat Import</h3>
    <p>The Badges page offers optional tools to import your game statistics from third-party stat-tracking
      services (currently <a href="https://www.agent-stats.com" target="_blank" rel="noopener noreferrer">Agent Stats</a>
      and <a href="https://the-grid.org" target="_blank" rel="noopener noreferrer">The Grid</a>). If you choose to use
      one, you provide an API key for that service, which we use to retrieve your statistics and match them against
      Ingress Plus badges. If you choose to save an API key to your profile for future use, it is stored alongside
      your other account data. These services are independent projects, not affiliated with or vetted by Ingress
      Plus - please review their own privacy practices before connecting an account.</p>

    <h2>2. Purposes of Data Usage</h2>
    <p>We use your data for the following purposes:</p>
    <ul>
        <li>Operating and maintaining the website and related plugins</li>
        <li>Ensuring site security and troubleshooting technical issues</li>
        <li>Providing personalized user experiences</li>
        <li>Contacting you via email for important site updates, such as changes to Terms of Service or security alerts</li>
        <li>Contacting you via email for other purposes, if you have opted in</li>
        <li>Displaying your Agent name, Faction, and badges publicly if your profile is set to public</li>
        <li>Retrieving your statistics from a third-party service you've connected, if you choose to use the optional stat import tool, to help identify which badges you've earned</li>
    </ul>

    <h2>3. User Rights</h2>
    <p>You have the following rights regarding your personal data:</p>
    <ul>
        <li><strong>Change your data:</strong> You can edit certain personal data (such as Agent name and Faction) via your profile settings, or you may contact the site admins for other changes.</li>
        <li><strong>Access your data:</strong> You may request a copy of your personal data by contacting the site admins.</li>
        <li><strong>Delete your data:</strong> You may request deletion of your personal data by contacting the site admins.</li>
    </ul>

    <h2>4. Contact</h2>
    <p>If you have any questions about this Privacy Policy or would like to exercise your rights,
      please contact the site administrators via <a href="mailto:help@ingress.plus"
      >help@ingress.plus</a
    >.</p>

    <h2>5. Changes to this Policy</h2>
    <p>We may update this Privacy Policy from time to time. We will notify users of any significant changes, and the latest version will always be available on our website.</p>
